// setLocaleLanguage updates the language used for text.
func (a *App) lang() lang {
	tag := a.cfg.Language
	if tag == "" {
		tag = a.locale
	}
	t := strings.ToLower(tag)
	switch {
	case strings.HasPrefix(t, "zh-hant") || strings.HasPrefix(t, "zh-tw") || strings.HasPrefix(t, "zh-hk") || strings.HasPrefix(t, "zh-mo"):
		return langHant
	case strings.HasPrefix(t, "zh"):
		return langZH
	default:
		return langEN
	}
}

// t returns the text of key in the current language.
func (a *App) t(key string) string {
	v, ok := texts[key]
	if !ok {
		return key
	}
	return v[a.lang()]
}

// tf formats a translated text.
func (a *App) tf(key string, args ...any) string {
	return fmt.Sprintf(a.t(key), args...)
}

// typeName returns the localized name of a file kind.
func (a *App) typeName(k fsx.Kind) string {
	switch k {
	case fsx.KindFolder:
		return a.t("typeFolder")
	case fsx.KindText:
		return a.t("typeText")
	case fsx.KindCode:
		return a.t("typeCode")
	case fsx.KindImage:
		return a.t("typeImage")
	case fsx.KindVideo:
		return a.t("typeVideo")
	case fsx.KindAudio:
		return a.t("typeAudio")
	case fsx.KindArchive:
		return a.t("typeArchive")
	case fsx.KindDocument:
		return a.t("typeDocument")
	case fsx.KindPDF:
		return a.t("typePDF")
	case fsx.KindSheet:
		return a.t("typeSheet")
	case fsx.KindSlides:
		return a.t("typeSlides")
	case fsx.KindExecutable:
		return a.t("typeExecutable")
	case fsx.KindFont:
		return a.t("typeFont")
	case fsx.KindDisk:
		return a.t("typeDisk")
	}
	return a.t("typeOther")
}

// typeLabel writes a file's type as Pulse does: TXT 文本文档, JPG 图片.
func (a *App) typeLabel(e fsx.Entry) string {
	if e.IsDir {
		return a.t("typeFolder")
	}
	name := a.typeName(e.Kind)
	if e.Ext == "" {
		return name
	}
	return strings.ToUpper(e.Ext) + " " + name
}
